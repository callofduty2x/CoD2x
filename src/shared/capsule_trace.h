#ifndef CAPSULE_TRACE_H
#define CAPSULE_TRACE_H

#include <stddef.h>

// Player hit detection using capsules attached to the skeleton, instead of the stock per-bone boxes.
// This file has no dependency on the game, so the geometry can be tested on its own.

enum capsuleBoneIndex_e
{
	CAP_J_SPINE1, CAP_J_SPINE2, CAP_J_SPINE4,
	CAP_J_NECK, CAP_J_HEAD,
	CAP_J_HIP_LE, CAP_J_HIP_RI,
	CAP_J_CLAVICLE_LE, CAP_J_CLAVICLE_RI,
	CAP_J_SHOULDER_LE, CAP_J_SHOULDER_RI,
	CAP_J_ELBOW_LE, CAP_J_ELBOW_RI,
	CAP_J_WRIST_LE, CAP_J_WRIST_RI,
	CAP_J_MID_LE_1, CAP_J_MID_LE_2, CAP_J_MID_LE_3,
	CAP_J_MID_RI_1, CAP_J_MID_RI_2, CAP_J_MID_RI_3,
	CAP_J_THUMB_LE_1, CAP_J_THUMB_LE_2, CAP_J_THUMB_LE_3,
	CAP_J_THUMB_RI_1, CAP_J_THUMB_RI_2, CAP_J_THUMB_RI_3,
	CAP_J_INDEX_LE_1, CAP_J_INDEX_LE_2, CAP_J_INDEX_LE_3,
	CAP_J_INDEX_RI_1, CAP_J_INDEX_RI_2, CAP_J_INDEX_RI_3,
	CAP_J_RING_LE_1, CAP_J_RING_LE_2, CAP_J_RING_LE_3,
	CAP_J_RING_RI_1, CAP_J_RING_RI_2, CAP_J_RING_RI_3,
	CAP_J_PINKY_LE_1, CAP_J_PINKY_LE_2, CAP_J_PINKY_LE_3,
	CAP_J_PINKY_RI_1, CAP_J_PINKY_RI_2, CAP_J_PINKY_RI_3,
	CAP_J_KNEE_LE, CAP_J_KNEE_RI,
	CAP_J_ANKLE_LE, CAP_J_ANKLE_RI,
	CAP_J_BALL_LE, CAP_J_BALL_RI,
	CAP_BONE_COUNT
};

extern const char* const capsule_bone_names[CAP_BONE_COUNT];

struct capsuleBone_t
{
	bool valid;
	unsigned short name;	// Script string id of the bone, reported back when this bone is hit
	float origin[3];
	float axis[3][3];		// Rows are the bone's local x, y and z axes
};

// Same memory layout as the game's trace result, see DObjTraceline
struct capsuleTraceResult_t
{
	float fraction;
	int surfaceType;
	float normal[3];
	unsigned short partName;
	unsigned short partGroup;
};

// Capsule sizes fitted to one player model. Anything left NULL in capsuleFit_t uses the shared sizes.
// capsule_models.cpp holds the tables, generated by tools/capsule_fit/generate_capsule_models.py
#define CAPSULE_TORSO_SLICES 5
#define CAPSULE_SKIRT_LEVELS 3

struct capsuleSliceFit_t
{
	float radius;
	float halfWidth;
	float forward;
};

// The part of a long coat that hangs around one leg. A radius of 0 means the model has no coat at this level.
struct capsuleSkirtFit_t
{
	float radius;
	float halfDepth;	// A coat is deeper from front to back than it is wide around one leg
	float forward;
};

struct capsuleBodyFit_t
{
	const char* name;
	capsuleSliceFit_t slices[CAPSULE_TORSO_SLICES];
	capsuleSliceFit_t trapezius;
	float hips;
	float upperArm[2];
	float forearm[2];
	float thigh[2];
	float shin[2];
	float foot[2];
	capsuleSkirtFit_t skirt[CAPSULE_SKIRT_LEVELS];
};

// Ends in the head bone's local space
struct capsuleHeadShape_t
{
	float localA[3];
	float localB[3];
	float radiusA;
	float radiusB;
};

struct capsuleHeadFit_t
{
	const char* name;
	capsuleHeadShape_t skull;
	capsuleHeadShape_t face;
};

struct capsuleHeadgearFit_t
{
	const char* name;
	capsuleHeadShape_t dome;
};

struct capsuleFit_t
{
	const capsuleBodyFit_t* body;
	const capsuleHeadFit_t* head;
	const capsuleHeadgearFit_t* headgear;
};

// Fills in the part of the fit this model provides, unknown models change nothing
void capsule_fit_add_model(capsuleFit_t* fit, const char* modelName);

// Convert the game's bone quaternion and weight into the axes used by capsule_trace()
void capsule_bone_set(capsuleBone_t* bone, const float* quat, const float* origin, float weight, unsigned short name);

// True when the skeleton has the bones of a player model
bool capsule_is_player_skeleton(const capsuleBone_t* bones);

// Trace from start to end. priorityMap gives the priority of each hit location and may be NULL.
// On entry, result->fraction is the furthest fraction to accept.
// Returns false if no capsule could be built, in which case the result is untouched.
bool capsule_trace(const capsuleBone_t* bones, const float* start, const float* end, const unsigned char* priorityMap, float scale, capsuleTraceResult_t* result, const capsuleFit_t* fit = NULL);

// Calls the callback with every capsule of the skeleton. These are the shapes capsule_trace() tests.
typedef void (*capsuleShapeCallback_t)(void* context, const float* a, const float* b, float radiusA, float radiusB, int hit, unsigned short partName);
void capsule_for_each_shape(const capsuleBone_t* bones, float scale, capsuleShapeCallback_t callback, void* context, const capsuleFit_t* fit = NULL);

// Calls the callback with the lines of a capsule's wireframe. Returns the number of lines.
typedef void (*capsuleLineCallback_t)(void* context, const float* start, const float* end);
int capsule_wireframe(const float* a, const float* b, float radiusA, float radiusB, capsuleLineCallback_t callback, void* context);

#endif
